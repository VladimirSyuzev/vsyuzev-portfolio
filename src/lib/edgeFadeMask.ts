import type { CSSProperties } from "react";

// edgeFadeMaskStyle — маска-затухание по краям для горизонтальных каруселей
// (трек «Процесс»/«Построение процесса», VariantsCarousel «Варианты»).
//
// На ≥1440 холст вёрстки зафиксирован в 1440px по центру экрана, а трек —
// full-bleed (во всю ширину окна). По просьбе пользователя: всё, что уезжает
// ЗА пределы центральной 1440-колонки, должно уходить в прозрачность —
// карточки/картинки появляются из неё и скрываются обратно, а не обрезаются
// жёстко по краю окна. Переход растянут РОВНО на ширину гаттера (от края
// экрана до края 1440-колонки).
//
// Раньше градиент собирался через CSS calc(100vw ...), но 100vw включает
// ширину системного скроллбара, а mask-image считается от РЕАЛЬНОГО бокса
// элемента (его clientWidth, без скроллбара). На экранах чуть шире 1440
// (где сам гаттер — 10-20px) это расхождение в 15-17px оказывалось больше
// гаттера: точка-стоп градиента вылезала за пределы бокса элемента, браузер
// схлопывал стопы — и переход пропадал целиком, оставался жёсткий обрез
// (воспроизведено на 1466px и 1481px). Поэтому берём РЕАЛЬНУЮ измеренную
// ширину контейнера (тот же clientWidth, что карусели уже меряют через
// ResizeObserver для расчёта отступов) и строим градиент в абсолютных
// пикселях этого бокса — никакого vw.
//
// Стопы — WHITE, не black (воспроизведено: в Chrome работало, в Firefox
// градиент вообще не проявлялся). Chrome трактует mask-image по
// alpha-каналу (важна только прозрачность), а Firefox по умолчанию — по
// luminance (яркости цвета): чёрный имеет яркость 0, поэтому Firefox
// читал «непрозрачный» чёрный стоп как «замаскировано», а не «видимо».
// Белый непрозрачный даёт alpha=1 И яркость=1 — корректно читается
// обоими механизмами одновременно.
//
// adaptive — включает край-фейд НА ЛЮБОЙ ширине (не только >1440). Нужен для
// карусели «варианты», которая full-bleed на всех размерах: карточки уходят
// в прозрачность у краёв и на планшете/мобайле тоже.
//   • >1440 — базовый фейд = гаттер (край экрана → край 1440-колонки).
//   • ≤1440 — базовый фейд ≈ 7% ширины, зажат в 20–56px.
// clearLeft / clearRight — фактический зазор (px) от края бокса до края
// АКТИВНОЙ («ключевой») карточки. Если передан — фейд с этой стороны
// ужимается так, чтобы не заходить на карточку (запас 6px); если карточка
// вплотную к краю или за ним — фейд этой стороны = 0.
type EdgeFadeOpts = {
  adaptive?: boolean;
  clearLeft?: number;
  clearRight?: number;
};

const SAFE_GAP = 6;

export function edgeFadeMaskStyle(
  measuredWidth: number | null | undefined,
  opts?: EdgeFadeOpts,
): CSSProperties | undefined {
  if (!measuredWidth) return undefined;

  let left: number;
  let right: number;
  if (measuredWidth > 1440) {
    // ≥1440 — гаттер до края центральной 1440-колонки; карточки туда не
    // заезжают своим центром, зазор до активной не учитываем (проверенное
    // поведение, см. репро 1466/1481).
    left = right = (measuredWidth - 1440) / 2;
  } else if (opts?.adaptive) {
    const base = Math.min(56, Math.max(20, measuredWidth * 0.07));
    left = right = base;
    // ужимаем фейд, чтобы он не наезжал на активную («ключевую») карточку
    if (opts.clearLeft != null) left = Math.max(0, Math.min(base, opts.clearLeft - SAFE_GAP));
    if (opts.clearRight != null) right = Math.max(0, Math.min(base, opts.clearRight - SAFE_GAP));
  } else {
    return undefined;
  }

  if (left < 1 && right < 1) return undefined;

  const gradient = `linear-gradient(
    to right,
    rgba(255,255,255,${left < 1 ? 1 : 0}) 0px,
    white ${left}px,
    white ${measuredWidth - right}px,
    rgba(255,255,255,${right < 1 ? 1 : 0}) ${measuredWidth}px
  )`;
  return {
    WebkitMaskImage: gradient,
    maskImage: gradient,
  };
}
