// Русская типографика — убирает «висячие» короткие слова (предлоги, союзы,
// частицы, короткие местоимения) в конце строк: приклеивает их к следующему
// слову неразрывным пробелом ( ). Плюс:
//  - тире не начинает строку («слово — слово»);
//  - число склеивается со следующим словом («226 иконок»);
//  - инициалы и «т. д.» / «и т. п.» не разрываются.
//
// Функция идемпотентна: повторный прогон уже обработанной строки ничего не
// меняет (после   регэкспы по обычному пробелу не срабатывают).
// Применяется глобально ко всему видимому тексту через <Typographer/>.

const NBSP = " ";

// Короткие слова, которые нельзя оставлять в конце строки.
const SHORT_WORDS = [
  // предлоги / союзы / частицы
  "а", "и", "в", "к", "о", "с", "у", "й",
  "из", "ко", "на", "не", "ни", "но", "во", "со", "об", "от", "по", "за",
  "до", "то", "же", "бы", "ли", "да", "уж",
  "для", "над", "под", "при", "про", "без", "как", "что", "или", "изо", "обо",
  "ещё", "еще", "уже", "вот", "тем",
  // короткие местоимения
  "я", "ты", "мы", "вы", "он",
  "их", "им", "её", "ей", "ее",
  "они", "она", "оно", "его", "ему", "нее", "неё", "чем", "мне", "нас", "вас",
];

const SHORT_ALT = SHORT_WORDS.join("|");

// Короткое слово на границе (начало строки / после пробела, скобки, кавычки,
// самого NBSP или дефиса) + пробелы + непробел → пробелы заменяем на NBSP.
const RE_SHORT = new RegExp(
  `(^|[\\s\\u00A0(«„"\\-–—])(${SHORT_ALT})[ \\t\\n]+(?=[^\\s])`,
  "giu",
);

// Тире между словами не должно начинать строку.
const RE_DASH = /(\S) +([–—]) +/g;

// Число + следующее слово держим вместе.
const RE_NUM = /(\d) +(?=[A-Za-zА-Яа-яЁё])/g;

// Инициалы и сокращения «т. д.», «т. е.», «и т. п.».
const RE_INITIALS = /([А-ЯЁ])\. +(?=[А-ЯЁ])/g;
const RE_ABBR = /(^|[\s (])([а-яё])\. +(?=[а-яё]\.)/giu;

export function typo(input: string): string {
  if (!input || input.indexOf(" ") === -1) return input;
  let s = input;
  // Прогоняем короткие слова до стабилизации — для цепочек вроде «и в тексте».
  for (let i = 0; i < 5; i++) {
    const next = s.replace(RE_SHORT, (_m, pre: string, word: string) => `${pre}${word}${NBSP}`);
    if (next === s) break;
    s = next;
  }
  s = s.replace(RE_DASH, `$1${NBSP}$2 `);
  s = s.replace(RE_NUM, `$1${NBSP}`);
  s = s.replace(RE_INITIALS, `$1.${NBSP}`);
  s = s.replace(RE_ABBR, `$1$2.${NBSP}`);
  return s;
}
