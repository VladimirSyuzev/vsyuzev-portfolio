// Правило "висячих предлогов": короткие предлоги, союзы и частицы не должны
// оставаться последним словом на строке — переносим их на следующую строку
// вместе со словом, к которому они относятся, заменяя обычный пробел после
// них на неразрывный ( ). Применяется к русскому текстовому контенту,
// который может переноситься на несколько строк.
const HANGING_WORDS = [
  "а", "и", "у", "о", "к", "с",
  "в", "во", "со", "ко", "об", "обо",
  "до", "из", "изо", "за", "на", "по", "от", "ото",
  "для", "без", "безо", "над", "надо", "под", "подо",
  "при", "про", "через", "чрез", "между", "меж",
  "но", "да", "же", "ли", "бы", "то", "не", "ни", "что", "как",
];

const PATTERN = new RegExp(`(^|\\s)(${HANGING_WORDS.join("|")})\\s+`, "giu");

export function preventOrphans(text: string): string {
  return text.replace(PATTERN, (_match, before: string, word: string) => `${before}${word} `);
}
