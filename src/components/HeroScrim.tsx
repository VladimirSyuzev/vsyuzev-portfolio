// HeroScrim — подложка обложки кейса под крупным номером «00X» и
// заголовком. Ключевое изображение hero растёт вместе с шириной экрана
// (FullBleedScale mode="grow"), а текстовый слой — нет: он остаётся в
// центрированной 1440-сетке. На широких мониторах «занятая» часть картинки
// (ноутбук, карты, билборд) заезжает ровно туда, где стоит заголовок, и
// белый текст становится нечитаемым.
//
// Решение (выбор пользователя — «картинка fullbleed + подложка»): поверх
// картинки, но под текстом — горизонтальный градиент цветом фона hero.
// Слева заливка полностью непрозрачна (там текст), к центру плавно уходит
// в прозрачность (там картинка видна как есть). Проценты-стопы берутся от
// ширины экрана, поэтому «сплошная» зона в пикселях сама расширяется на
// широких мониторах и всегда закрывает центрированный текст. У левого края,
// где картинки нет, подложка совпадает с фоном hero и незаметна.
//
// color — цвет фона hero у левого края (сэмпл из макета Figma):
//   кейс 1 — #212121, кейс 2 — #1b1b21, кейс 3 — #0b1266,
//   кейс 4 — #2b57b4, кейс 5 — #4d0000.
export default function HeroScrim({ color }: { color: string }) {
  return (
    <div
      className="pointer-events-none absolute inset-0 z-[1]"
      style={{
        background: `linear-gradient(90deg, ${color} 0%, ${color} 21%, transparent 54%)`,
      }}
    />
  );
}
